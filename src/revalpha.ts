/* Ambang NCC: 0.60. Di latar yang cukup rata, korelasi alpha vs luminansi
   mendekati 1 (luminansi = orig + alpha*(255-orig), linear terhadap
   alpha); di latar bertekstur skor turun. 0.60 = konservatif: lebih baik
   gagal jujur daripada menghapus piksel yang bukan sparkle. */
export const NCC_MIN = 0.6;
const SEARCH_STEP = 8;
const SEARCH_RANGE = 16;

function decodeAlpha(b64: string, size: number): Float32Array {
  const bin = atob(b64);
  if (bin.length < size * size) throw new Error("alpha map rusak: " + bin.length + " byte, butuh " + (size * size));
  const out = new Float32Array(size * size);
  for (let i = 0; i < size * size; i++) out[i] = bin.charCodeAt(i) / 255;
  return out;
}

let alpha48: Float32Array | null = null;
let alpha96: Float32Array | null = null;
export function getAlphaMap(size: 48 | 96): Float32Array {
  if (size === 48) { if (!alpha48) alpha48 = decodeAlpha(ALPHA_48_B64, 48); return alpha48; }
  if (!alpha96) alpha96 = decodeAlpha(ALPHA_96_B64, 96); return alpha96;
}

export interface ImgLike { data: Uint8ClampedArray; width: number; height: number }

/* Normalized cross-correlation antara luminansi gambar di dalam box dan
   alpha map template. Mengembalikan -1..1. */
export function nccScore(img: ImgLike, box: SparkleBox, alpha: Float32Array): number {
  const { data, width: W } = img;
  const n = box.w * box.h;
  let sumA = 0, sumL = 0;
  for (let i = 0; i < n; i++) sumA += alpha[i];
  const meanA = sumA / n;
  // Luminansi dulu (satu pass) — butuh mean luminansi sebelum korelasi.
  const lum = new Float32Array(n);
  for (let y = 0; y < box.h; y++) {
    for (let x = 0; x < box.w; x++) {
      const p = ((box.y + y) * W + (box.x + x)) * 4;
      lum[y * box.w + x] = 0.2126 * data[p] + 0.7152 * data[p + 1] + 0.0722 * data[p + 2];
      sumL += lum[y * box.w + x];
    }
  }
  const meanL = sumL / n;
  let num = 0, denA = 0, denL = 0;
  for (let i = 0; i < n; i++) {
    const da = alpha[i] - meanA, dl = lum[i] - meanL;
    num += da * dl; denA += da * da; denL += dl * dl;
  }
  if (denA <= 0 || denL <= 0) return -1;
  const r = num / Math.sqrt(denA * denL);
  return Number.isFinite(r) ? r : -1; // NaN tidak boleh lolos sebagai skor
}

function canonicalBox(imgW: number, imgH: number, size: 48 | 96): SparkleBox {
  const margin = size === 96 ? 64 : 32;
  return { x: imgW - margin - size, y: imgH - margin - size, w: size, h: size };
}

/* Cari sparkle Gemini: dua ukuran kanonis di pojok kanan bawah + geser
   lokal +-16px (toleransi crop/re-encode). Skor terbaik >= NCC_MIN =
   terkonfirmasi; di bawah itu = tidak ketemu (jujur, bukan nebak). */
export function detectGeminiSparkle(img: ImgLike): SparkleHit | null {
  const { width: W, height: H } = img;
  if (W < 96 || H < 96) return null;
  let best: SparkleHit | null = null;
  for (const size of [48, 96] as const) {
    if (W < size + 32 || H < size + 32) continue;
    const alpha = getAlphaMap(size);
    const base = canonicalBox(W, H, size);
    for (let dy = -SEARCH_RANGE; dy <= SEARCH_RANGE; dy += SEARCH_STEP) {
      for (let dx = -SEARCH_RANGE; dx <= SEARCH_RANGE; dx += SEARCH_STEP) {
        const box = { x: base.x + dx, y: base.y + dy, w: size, h: size };
        if (box.x < 0 || box.y < 0 || box.x + box.w > W || box.y + box.h > H) continue;
        const score = nccScore(img, box, alpha);
        if (!best || score > best.score) {
          // Latar gelap? (rata-rata luminansi box < 60) — unblend bisa
          // menyisakan bayangan tipis; ditulis jujur di UI.
          let sumL = 0; const n = box.w * box.h;
          for (let y = 0; y < box.h; y += 4) for (let x = 0; x < box.w; x += 4) {
            const p = ((box.y + y) * W + (box.x + x)) * 4;
            sumL += 0.2126 * img.data[p] + 0.7152 * img.data[p + 1] + 0.0722 * img.data[p + 2];
          }
          const meanL = sumL / Math.ceil(n / 16);
          best = { box, score, size, darkBg: meanL < 60 };
        }
      }
    }
  }
  // !(score >= NCC_MIN) — bukan (score < NCC_MIN): NaN harus gagal,
  // bukan lolos (NaN < 0.6 === false). Lihat tes revalpha.test.mjs.
  if (!best || !(best.score >= NCC_MIN)) return null;
  return best;
}

/* Balik alpha blending per piksel di dalam box. Piksel di luar box
   byte-identical (disalin apa adanya). Alpha >= 0.95 tidak bisa
   dipulihkan (pembagi ~0) — piksel itu dibiarkan, dihitung di
   unrecoverable. Alpha maksimum map ini ~0.51, jadi praktis tidak ada
   piksel yang tak-terpulihkan. */
export function removeSparkle(img: ImgLike, hit: SparkleHit): { image: ImageData; unrecoverable: number } {
  const { box, size } = hit;
  const alpha = getAlphaMap(size);
  const out = new ImageData(new Uint8ClampedArray(img.data), img.width, img.height);
  let unrecoverable = 0;
  for (let y = 0; y < box.h; y++) {
    for (let x = 0; x < box.w; x++) {
      const a = alpha[y * box.w + x];
      if (a <= 0.01) continue;
      const p = ((box.y + y) * img.width + (box.x + x)) * 4;
      if (a >= 0.95) { unrecoverable++; continue; }
      const inv = 1 / (1 - a);
      for (let c = 0; c < 3; c++) {
        const v = (img.data[p + c] - a * 255) * inv;
        out.data[p + c] = v < 0 ? 0 : v > 255 ? 255 : v;
      }
    }
  }
  return { image: out, unrecoverable };
}
